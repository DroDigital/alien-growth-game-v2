//! CREDITS.md generation from the asset manifest.

use game_core::manifest::{AssetKind, AssetManifest};
use std::collections::BTreeMap;
use std::fmt::Write;

fn kind_title(kind: AssetKind) -> &'static str {
    match kind {
        AssetKind::Hdri => "HDRIs",
        AssetKind::Texture => "Textures",
        AssetKind::Model => "Models",
        AssetKind::Sfx => "Sound effects",
        AssetKind::Music => "Music",
        AssetKind::Font => "Fonts",
    }
}

pub fn render(manifest: &AssetManifest) -> String {
    let mut out = String::new();
    out.push_str("# Credits\n\n");
    out.push_str(
        "<!-- Generated by `cargo agtool credits` from assets/manifest.json. Do not edit. -->\n\n",
    );
    out.push_str(
        "Third-party assets used by the game. Every asset also has a procedural \
fallback, so builds without downloads still work.\n\n",
    );
    if manifest.assets.is_empty() {
        out.push_str("No third-party assets yet.\n");
        return out;
    }
    let mut by_kind: BTreeMap<&'static str, Vec<_>> = BTreeMap::new();
    for a in &manifest.assets {
        by_kind.entry(kind_title(a.kind)).or_default().push(a);
    }
    for (title, mut assets) in by_kind {
        assets.sort_by(|a, b| a.id.cmp(&b.id));
        let _ = writeln!(out, "## {title}\n");
        out.push_str("| Asset | Author | License | Source |\n|---|---|---|---|\n");
        for a in assets {
            let pack = if a.ultra_pack { " (Ultra pack)" } else { "" };
            let _ = writeln!(
                out,
                "| `{}`{pack} | {} | {} | [link]({}) |",
                a.id, a.author, a.license, a.page_url
            );
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use game_core::manifest::AssetEntry;

    #[test]
    fn renders_table_rows_sorted() {
        let mk = |id: &str| AssetEntry {
            id: id.into(),
            kind: AssetKind::Texture,
            path: format!("textures/{id}.ktx2"),
            source_url: "https://example.org/x".into(),
            page_url: "https://example.org".into(),
            author: "Someone".into(),
            license: "CC0-1.0".into(),
            source_sha256: None,
            sha256: None,
            fallback: "flat".into(),
            ultra_pack: false,
        };
        let m = AssetManifest {
            version: 1,
            assets: vec![mk("b"), mk("a")],
        };
        let text = render(&m);
        assert!(text.contains("## Textures"));
        assert!(text.find("`a`").unwrap() < text.find("`b`").unwrap());
    }
}
